#!/usr/bin/env python3
"""Bundle css/*.css (in css/manifest.txt order) into one minified toki.css.

Usage:  python3 scripts/build-css.py          write toki.css
        python3 scripts/build-css.py --check  exit 1 if toki.css is out of date

The order in manifest.txt IS the cascade order: later files win.
Edit the files in css/, never toki.css.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "toki.css"

def minify(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)       # comments
    css = re.sub(r"\s+", " ", css)                         # whitespace runs
    css = re.sub(r"\s*([{};])\s*", r"\1", css)             # around structural characters
    css = re.sub(r";}", "}", css)                          # trailing semicolons
    return css.strip()

def build() -> str:
    names = [n for n in (ROOT / "css" / "manifest.txt").read_text().split() if n]
    parts = [f"/* {n}.css */\n{minify((ROOT / 'css' / f'{n}.css').read_text(encoding='utf-8'))}" for n in names]
    header = "/* TOKI SATSUEI bundle. GENERATED by scripts/build-css.py from css/*.css. Do not edit. */\n"
    return header + "\n".join(parts) + "\n"

if __name__ == "__main__":
    built = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != built:
            sys.exit("toki.css is out of date: run `python3 scripts/build-css.py` and commit the result.")
        print("toki.css is up to date")
    else:
        OUT.write_text(built, encoding="utf-8")
        print(f"Wrote {OUT.name}: {len(built):,} bytes from {len(built.splitlines())-1} sources")


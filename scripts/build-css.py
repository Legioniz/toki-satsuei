#!/usr/bin/env python3
"""Bundle each page's stylesheets into one file, preserving the existing cascade order.

Source files stay the place to edit. Run `python scripts/build-css.py` after changing any of them,
and commit the toki-*.css bundles. `--check` fails if a bundle is out of date (used by CI).
The minifier is deliberately conservative (comments and whitespace only), so rendering is identical.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLES = {
    "toki-home.css": ["styles", "refinement", "policies", "availability", "motion-system", "cinematic", "experience", "fixes", "pricing-calculator", "design-system", "orientation"],
    "toki-archive.css": ["styles", "library", "refinement", "motion-system", "cinematic", "experience", "pages", "design-system", "orientation"],
    "toki-policies.css": ["styles", "refinement", "policies", "motion-system", "cinematic", "experience", "pages", "design-system", "orientation"],
    "toki-404.css": ["styles", "refinement", "policies", "motion-system", "cinematic", "experience", "pages", "design-system", "orientation"],
    "toki-admin.css": ["styles", "refinement", "motion-system", "admin", "design-system", "orientation"],
    "toki-client.css": ["styles", "refinement", "motion-system", "client-gallery", "design-system", "orientation"],
}

def minify(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{};,])\s*", r"\1", css)
    css = re.sub(r":\s+", ":", css)
    css = css.replace(";}", "}")
    return css.strip()

def build(name: str) -> str:
    parts = [minify((ROOT / f"{src}.css").read_text(encoding="utf-8")) for src in BUNDLES[name]]
    header = f"/* {name}: generated by scripts/build-css.py from {', '.join(s + '.css' for s in BUNDLES[name])}. */\n"
    return header + "\n".join(parts) + "\n"

def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for name in BUNDLES:
        out = build(name)
        path = ROOT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != out:
                stale.append(name)
        else:
            path.write_text(out, encoding="utf-8")
            print(f"{name}: {len(out):,} bytes")
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run python scripts/build-css.py and commit the result.")
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
